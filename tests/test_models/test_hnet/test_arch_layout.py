class TestShippedLayoutsParseToTheHandWrittenTree:
    """Every shipped layout string parses to its hand-derived structure."""

    @pytest.mark.parametrize("variant", sorted(SHIPPED_LAYOUTS))
    def test_layout_parses_to_the_hand_written_tree(self, variant):
        layout, expected = SHIPPED_LAYOUTS[variant]
        assert as_tree(parse_arch_layout(layout)) == expected

    @pytest.mark.parametrize("variant", sorted(SHIPPED_LAYOUTS))
    def test_the_variant_row_carries_that_same_layout(self, variant):
        layout, expected = SHIPPED_LAYOUTS[variant]
        assert as_tree(MODEL_VARIANTS[variant].stage_spec) == expected

    def test_the_six_trees_are_not_all_the_same(self):
        """The 'agrees' twin: four distinct trees across the six variants.

        The two XL 2-stage variants differ from each other and from the L one only in the
        innermost group, so a parser that ignored the inner layout string would make all
        four 2-stage trees equal.
        """
        trees = {as_tree(cfg.stage_spec) for cfg in MODEL_VARIANTS.values()}
        assert len(trees) == 6

    def test_a_wrong_inner_count_is_not_accepted_as_equal(self):
        """T26 and T27 must not parse to the same tree."""
        assert as_tree(parse_arch_layout(["m4", ["T26"], "m4"])) != as_tree(
            parse_arch_layout(["m4", ["T27"], "m4"])
        )


class TestLetterSemantics:
    """Letter identity picks the mixer; letter CASE picks whether an MLP is present."""

    @pytest.mark.parametrize(
        "kind,mixer,has_mlp,height",
        [
            ("m", MIXER_MAMBA2, False, 3),
            ("M", MIXER_MAMBA2, True, 6),
            ("t", MIXER_ATTENTION, False, 3),
            ("T", MIXER_ATTENTION, True, 6),
        ],
    )
    def test_block_semantics(self, kind, mixer, has_mlp, height):
        block = BlockSpec(kind=kind, n_layer=3)
        assert block.mixer == mixer
        assert block.has_mlp is has_mlp
        assert block.height == height

    def test_case_changes_the_height_of_the_same_letter(self):
        """The 'differ' twin for case sensitivity: m4 is 4, M4 is 8."""
        lower = parse_arch_layout(["m4"])
        upper = parse_arch_layout(["M4"])
        assert lower.main.height == 4
        assert upper.main.height == 8
        assert lower.main.height != upper.main.height

    def test_case_does_not_change_the_mixer_family(self):
        """The 'agree' twin: case is orthogonal to mixer identity."""
        assert BlockSpec("m", 1).mixer == BlockSpec("M", 1).mixer
        assert BlockSpec("t", 1).mixer == BlockSpec("T", 1).mixer
        assert BlockSpec("m", 1).mixer != BlockSpec("t", 1).mixer

    def test_case_is_preserved_in_the_parsed_kind(self):
        assert parse_arch_layout(["M4"]).main.blocks[0].kind == "M"
        assert parse_arch_layout(["m4"]).main.blocks[0].kind == "m"

    def test_arch_full_expands_groups_in_order(self):
        spec = parse_arch_layout(["m2T1"])
        assert spec.main.arch_full == ("m", "m", "T")
        assert parse_arch_layout(["T1m2"]).main.arch_full == ("T", "m", "m")

    def test_group_order_matters(self):
        """'differ' twin for order: m4T1 and T1m4 have equal height but differ."""
        a = parse_arch_layout(["m4T1"]).main
        b = parse_arch_layout(["T1m4"]).main
        assert a.height == b.height == 6
        assert a.arch_full != b.arch_full


class TestEncoderDecoderSlots:
    """Slot 0 is the encoder and slot 2 is the decoder -- never the other way round."""

    def test_shipped_stage_one_slots_are_not_interchangeable(self):
        """`T1m4` is the stage-1 encoder and `m4T1` the stage-1 decoder."""
        spec = parse_arch_layout(SHIPPED_LAYOUTS["hnet_2stage_XL"][0])
        assert spec.main.encoder.layout == "T1m4"
        assert spec.main.decoder.layout == "m4T1"
        assert spec.main.encoder.layout != spec.main.decoder.layout

    def test_an_asymmetric_layout_keeps_its_slots(self):
        spec = parse_arch_layout(["m1", ["T2"], "t3"])
        assert (spec.encoder.layout, spec.encoder.role) == ("m1", "encoder")
        assert (spec.decoder.layout, spec.decoder.role) == ("t3", "decoder")

    def test_a_symmetric_layout_agrees_on_both_slots(self):
        """'agree' twin: when the two strings are equal the two stacks match."""
        spec = parse_arch_layout(["m4", ["T2"], "m4"])
        assert spec.encoder.blocks == spec.decoder.blocks
        assert spec.encoder.role != spec.decoder.role


class TestNesting:
    """The middle slot recurses; stage indices count from the outside in."""

    @pytest.mark.parametrize(
        "variant,expected_stages",
        [
            ("hnet_1stage_L", 2),
            ("hnet_1stage_XL", 2),
            ("hnet_2stage_L", 3),
            ("hnet_2stage_XL", 3),
            ("hnet_2stage_XL_chinese", 3),
            ("hnet_2stage_XL_code", 3),
        ],
    )
    def test_stage_count(self, variant, expected_stages):
        assert stage_count(MODEL_VARIANTS[variant].stage_spec) == expected_stages
        assert MODEL_VARIANTS[variant].num_stages == expected_stages

    def test_one_stage_and_two_stage_counts_differ(self):
        """'differ' twin: recursion that stopped early would flatten these to equal."""
        assert stage_count(parse_arch_layout(["m4", ["T22"], "m4"])) != stage_count(
            parse_arch_layout(["m4", ["T1m4", ["T27"], "m4T1"], "m4"])
        )

    def test_only_the_innermost_stage_is_marked_innermost(self):
        spec = parse_arch_layout(SHIPPED_LAYOUTS["hnet_2stage_XL"][0])
        assert spec.is_innermost is False
        assert spec.main.is_innermost is False
        assert spec.main.main.is_innermost is True

    def test_the_innermost_stage_has_no_encoder_or_decoder(self):
        inner = parse_arch_layout(SHIPPED_LAYOUTS["hnet_2stage_XL"][0]).main.main
        assert inner.encoder is None
        assert inner.decoder is None
        assert isinstance(inner.main, IsotropicSpec)

    def test_stage_indices_increase_by_one_inward(self):
        spec = parse_arch_layout(SHIPPED_LAYOUTS["hnet_2stage_XL"][0])
        assert spec.stage_idx == 0
        assert spec.encoder.stage_idx == 0
        assert spec.main.stage_idx == 1
        assert spec.main.encoder.stage_idx == 1
        assert spec.main.main.stage_idx == 2
        assert spec.main.main.main.stage_idx == 2

    def test_deep_nesting_beyond_the_shipped_configs(self):
        """D-001: the port carries the full generality, not just 1- and 2-stage."""
        spec = parse_arch_layout(["m1", ["m1", ["m1", ["t1"], "m1"], "m1"], "m1"])
        assert stage_count(spec) == 4
        assert spec.main.main.main.is_innermost is True


class TestNResiduals:
    r"""``n_residuals`` sums ``Isotropic.height`` over the WHOLE nested hierarchy.

    Worked derivation for ``hnet_1stage_L`` (``configs/hnet_1stage_L.json``,
    ``arch_layout = ["m4", ["T22"], "m4"]``), restated per F-01 section 8:

    * encoder ``m4``  -- lowercase, so ``+4``  (mixer only writes the residual stream)
    * decoder ``m4``  -- lowercase, so ``+4``
    * innermost ``T22`` -- UPPERCASE, so ``+2 * 22 = +44`` (mixer AND SwiGLU MLP)

    Total ``4 + 4 + 44 = 52``. This is the denominator of the depth-scaled init
    ``std = 0.02 / sqrt(n_residuals)``, so a wrong value silently mis-scales every
    residual-writing projection in the model.
    """

    def test_hnet_1stage_l_is_52(self):
        assert n_residuals(MODEL_VARIANTS["hnet_1stage_L"].stage_spec) == 52
        assert MODEL_VARIANTS["hnet_1stage_L"].n_residuals == 52

    @pytest.mark.parametrize(
        "variant,expected",
        [
            # 4 (m4 enc) + 4 (m4 dec) + 2*22 = 52
            ("hnet_1stage_L", 52),
            # 4 + 4 + 2*24 = 56
            ("hnet_1stage_XL", 56),
            # 4 + 4 | 6 (T1m4 = 2+4) + 6 (m4T1 = 4+2) | 2*26 = 8 + 12 + 52 = 72
            ("hnet_2stage_L", 72),
            # 8 + 12 + 2*27 = 74
            ("hnet_2stage_XL", 74),
            # 8 + 12 + 2*30 = 80
            ("hnet_2stage_XL_chinese", 80),
            # 8 + 12 + 2*28 = 76
            ("hnet_2stage_XL_code", 76),
        ],
    )
    def test_every_variant(self, variant, expected):
        assert n_residuals(MODEL_VARIANTS[variant].stage_spec) == expected

    def test_uppercase_doubles_and_lowercase_does_not(self):
        """'differ' twin for the +2n rule: the same counts, opposite case."""
        assert n_residuals(parse_arch_layout(["m4", ["t22"], "m4"])) == 30
        assert n_residuals(parse_arch_layout(["m4", ["T22"], "m4"])) == 52
        assert n_residuals(parse_arch_layout(["M4", ["T22"], "M4"])) == 60

    def test_it_spans_the_whole_hierarchy_not_one_stage(self):
        """Dropping any level would make this equal to a strict subset's total."""
        spec = MODEL_VARIANTS["hnet_2stage_XL"].stage_spec
        inner_only = spec.main.main.main.height
        assert inner_only == 54
        assert n_residuals(spec) == 74
        assert n_residuals(spec) != inner_only

    def test_by_stage_is_the_reference_outside_in_cumulative(self):
        """``hnet.py:121-147`` threads ``parent_residuals`` inward, one value per stage.

        ``hnet_1stage_L``: the outer m4/m4 sandwich is scaled against 4 + 4 = 8, and the
        innermost T22 against 8 + 44 = 52.
        """
        assert n_residuals_by_stage(MODEL_VARIANTS["hnet_1stage_L"].stage_spec) == (
            8,
            52,
        )
        assert n_residuals_by_stage(MODEL_VARIANTS["hnet_2stage_XL"].stage_spec) == (
            8,
            20,
            74,
        )

    def test_the_last_cumulative_equals_the_hierarchy_total(self):
        for name, cfg in MODEL_VARIANTS.items():
            spec = cfg.stage_spec
            assert n_residuals_by_stage(spec)[-1] == n_residuals(spec), name

    def test_the_earlier_cumulatives_do_not(self):
        """'differ' twin: only the LAST element coincides with the total."""
        spec = MODEL_VARIANTS["hnet_2stage_XL"].stage_spec
        assert n_residuals_by_stage(spec)[0] != n_residuals(spec)
        assert n_residuals_by_stage(spec)[1] != n_residuals(spec)


