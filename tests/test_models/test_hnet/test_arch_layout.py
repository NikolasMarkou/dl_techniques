"""Guards for the H-Net ``arch_layout`` mini-language parser and variant table.

What this file pins
-------------------
1. The parse of EVERY shipped layout string, against a HAND-WRITTEN expected tree.
   "Hand-written" is load-bearing: the expected structures below were transcribed by
   reading ``/media/arxwn/data_fast/repositories/hnet/configs/*.json`` and applying the
   grammar by hand. None of them was produced by calling the parser and pasting its
   output -- a pin generated by the code under test validates nothing.
2. The ``n_residuals`` arithmetic, restated in prose in each test's docstring so that a
   future reader can re-derive it without running anything.
3. The six variant rows, each against the numbers in its own JSON file, so a row
   transcribed from the wrong JSON fails.
4. The validation arms: malformed layout strings, unknown letters, wrong-length lists,
   out-of-range and negative stage indices.

Every "these agree" assertion has a "these differ" twin: an equality that would also hold
if the parser collapsed the distinction it is meant to preserve is not a guard.

The subject is pure Python -- no Keras import, no backend, no device.
"""

