class TestArchConfigValidation:
    """Per-stage list lengths must agree with the layout's stage count."""

    def _kwargs(self, **overrides):
        base = dict(
            arch_layout=["m4", ["T22"], "m4"],
            d_model=[1024, 1536],
            d_intermediate=[0, 4096],
            attn_cfg=AttnSpec(
                num_heads=[16, 16], rotary_emb_dim=[32, 48], window_size=[1023, -1]
            ),
        )
        base.update(overrides)
        return base

    def test_the_baseline_builds(self):
        """'agree' twin for every rejection below."""
        assert HNetArchConfig(**self._kwargs()).num_stages == 2

    @pytest.mark.parametrize(
        "field,value",
        [
            ("d_model", [1024]),
            ("d_model", [1024, 1536, 2048]),
            ("d_intermediate", [0]),
        ],
    )
    def test_a_wrong_length_per_stage_list_raises(self, field, value):
        with pytest.raises(ValueError, match="declares 2 stages"):
            HNetArchConfig(**self._kwargs(**{field: value}))

    def test_a_wrong_length_attn_list_raises(self):
        bad = AttnSpec(num_heads=[16], rotary_emb_dim=[32, 48], window_size=[1023, -1])
        with pytest.raises(ValueError, match="attn_cfg.num_heads"):
            HNetArchConfig(**self._kwargs(attn_cfg=bad))

    def test_a_malformed_layout_is_rejected_at_construction(self):
        with pytest.raises(ValueError, match="malformed"):
            HNetArchConfig(**self._kwargs(arch_layout=["m4", ["T22x"], "m4"]))

    def test_a_non_positive_d_model_raises(self):
        with pytest.raises(ValueError, match="d_model must be positive"):
            HNetArchConfig(**self._kwargs(d_model=[1024, 0]))

    def test_a_non_integer_d_model_raises(self):
        with pytest.raises(TypeError, match="only integers"):
            HNetArchConfig(**self._kwargs(d_model=[1024, 1536.0]))

    def test_lists_are_stored_as_tuples_so_shared_rows_cannot_be_mutated(self):
        cfg = HNetArchConfig(**self._kwargs())
        assert isinstance(cfg.d_model, tuple)
        assert isinstance(cfg.attn_cfg.window_size, tuple)
        with pytest.raises(TypeError):
            cfg.d_model[0] = 1


class TestPlainDictRoundTrip:
    """``to_dict``/``from_dict`` round-trip by value, JSON-shaped."""

    @pytest.mark.parametrize("variant", sorted(SHIPPED_LAYOUTS))
    def test_round_trip_is_identity(self, variant):
        cfg = MODEL_VARIANTS[variant]
        assert HNetArchConfig.from_dict(cfg.to_dict()) == cfg

    def test_to_dict_is_json_shaped(self):
        import json

        payload = MODEL_VARIANTS["hnet_2stage_XL"].to_dict()
        assert json.loads(json.dumps(payload)) == payload
        assert payload["arch_layout"] == ["m4", ["T1m4", ["T27"], "m4T1"], "m4"]

    def test_two_different_variants_do_not_round_trip_to_each_other(self):
        """'differ' twin: a round-trip that dropped a field would collapse these."""
        a = HNetArchConfig.from_dict(MODEL_VARIANTS["hnet_2stage_XL"].to_dict())
        b = HNetArchConfig.from_dict(MODEL_VARIANTS["hnet_2stage_XL_code"].to_dict())
        assert a != b

    def test_an_unknown_key_is_rejected_not_ignored(self):
        payload = MODEL_VARIANTS["hnet_1stage_L"].to_dict()
        payload["chunk_size"] = 256
        with pytest.raises(KeyError, match="unknown HNetArchConfig keys"):
            HNetArchConfig.from_dict(payload)

    def test_a_missing_required_key_raises(self):
        payload = MODEL_VARIANTS["hnet_1stage_L"].to_dict()
        del payload["d_model"]
        with pytest.raises(KeyError, match="missing required"):
            HNetArchConfig.from_dict(payload)


