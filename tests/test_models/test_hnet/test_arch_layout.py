# HAND-WRITTEN expected trees, one per shipped config.
# Derivation of each `height`: lowercase letter contributes n_layer, uppercase
# contributes 2 * n_layer (mixer + SwiGLU MLP each write the residual stream).
# ---------------------------------------------------------------------

