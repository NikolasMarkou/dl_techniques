class TestLayoutValidation:
    """Malformed layouts fail loudly instead of parsing to something smaller."""

    @pytest.mark.parametrize(
        "bad",
        ["m", "4", "m4x", "xm4", "m4 T1", "m4,T1", "m-4", "mm4", "m4T"],
    )
    def test_malformed_layout_strings_raise(self, bad):
        with pytest.raises(ValueError, match="malformed|empty"):
            parse_arch_layout([bad])

    @pytest.mark.parametrize("letter", ["a", "q", "s", "n", "x", "Z"])
    def test_unknown_letters_raise(self, letter):
        with pytest.raises(ValueError, match="malformed|empty"):
            parse_arch_layout([f"{letter}4"])

    def test_re_findall_alone_would_have_silently_dropped_the_junk(self):
        """Why the exact-reconstruction check exists, stated as a measurement.

        ``re.findall`` on ``"m4x"`` happily returns ``[("m", "4")]``. Without the
        reconstruction check the parser would build a 4-layer Mamba stack from a string
        the user did not write.
        """
        assert re.findall(r"([mMtT])(\d+)", "m4x") == [("m", "4")]
        with pytest.raises(ValueError):
            parse_arch_layout(["m4x"])

    def test_a_zero_layer_group_raises(self):
        with pytest.raises(ValueError, match="at least one block"):
            parse_arch_layout(["m0"])

    @pytest.mark.parametrize("length", [0, 2, 4, 5])
    def test_wrong_length_layout_lists_raise(self, length):
        with pytest.raises(ValueError, match="length"):
            parse_arch_layout(["m1"] * length)

    def test_lengths_one_and_three_are_accepted(self):
        """'agree' twin for the length check."""
        assert parse_arch_layout(["m1"]).is_innermost is True
        assert parse_arch_layout(["m1", ["t1"], "m1"]).is_innermost is False

    def test_a_bare_string_is_not_a_layout(self):
        with pytest.raises(TypeError, match="must be a list"):
            parse_arch_layout("m4")

    def test_a_non_innermost_middle_slot_must_be_a_list(self):
        with pytest.raises(TypeError, match="must be a list"):
            parse_arch_layout(["m4", "T22", "m4"])

    def test_an_encoder_slot_must_be_a_string(self):
        with pytest.raises(TypeError, match="must be a string"):
            parse_arch_layout([["m4"], ["T22"], "m4"])

    def test_the_innermost_slot_must_be_a_string(self):
        with pytest.raises(TypeError, match="must be a string"):
            parse_arch_layout([["m4"]])


