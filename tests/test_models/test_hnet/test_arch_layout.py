# ---------------------------------------------------------------------
# A read-only view of a parsed tree, so the hand-written pins stay readable.
# ---------------------------------------------------------------------


def as_tree(node):
    """Flatten a parsed node into nested tuples of plain values.

    Reads only public attributes; it introduces no parsing logic of its own, so the
    expected literals below remain hand-derived rather than machine-generated.
    """
    if isinstance(node, IsotropicSpec):
        return (
            "iso",
            node.layout,
            node.stage_idx,
            node.role,
            tuple((b.kind, b.n_layer) for b in node.blocks),
            node.height,
        )
    assert isinstance(node, StageSpec)
    return (
        "stage",
        node.stage_idx,
        node.is_innermost,
        None if node.encoder is None else as_tree(node.encoder),
        as_tree(node.main),
        None if node.decoder is None else as_tree(node.decoder),
    )


