"""Frozen independent reference: the OFFICIAL ``mistralai/timestral`` torch model's outputs.

``data/torch_reference.npz`` was generated by running the official package (see
``data/generate_torch_reference.py`` for the commit, torch version and recipe) on CPU. It
holds the torch state dict in the released checkpoint format, the inputs and the official
outputs, so this suite checks the Keras port against an implementation nobody on this
project wrote, WITHOUT torch. The state dict is written to a ``model.safetensors`` and
read by ``load_model``, the path a released Hugging Face checkpoint takes.

Tolerances are derived, not fitted: float32, about 20 rounded stages per layer, four
layers, each stage a few eps32 of relative error, so the bound is
``4 * 20 * 4 * eps32 * (1 + max|value|)``. Before 2026-10-19 (plan-2026-10-14T062616-81938e81
D-166) ``load_model`` could not read the released names at all, and once it could, the
port's fused-QKV head split moved ``predict_block`` by about 1e5 on the released 5M weights.
"""

import json
from pathlib import Path

import numpy as np
import pytest

import keras

from dl_techniques.models.time_series.timestral.config import TimestralConfig
from dl_techniques.models.time_series.timestral.loading import load_model, save_safetensors
from tests.numerics import true_float32_matmul

REFERENCE = Path(__file__).parent / "data" / "torch_reference.npz"
_EPS32 = float(np.finfo(np.float32).eps)
_STAGES, _LAYERS = 20, 4


def _tol(expected):
    return 4 * _STAGES * _LAYERS * _EPS32 * (1.0 + float(np.abs(expected).max()))


@pytest.fixture(autouse=True)
def _true_float32():
    """TF32 matmul would turn the float32 comparison into a ~1e-4 one on a GPU."""
    with true_float32_matmul():
        yield


@pytest.fixture(scope="module")
def reference():
    return np.load(REFERENCE)


@pytest.fixture(scope="module")
def checkpoint(reference, tmp_path_factory):
    """The reference state dict as a released-format checkpoint directory."""
    directory = tmp_path_factory.mktemp("timestral_reference")
    TimestralConfig.from_dict(json.loads(str(reference["config_json"]))).save(
        directory / "config.json")
    save_safetensors({k[len("w__"):]: reference[k] for k in reference.files
                      if k.startswith("w__")}, directory / "model.safetensors")
    return directory


@pytest.fixture(scope="module")
def model(checkpoint):
    return load_model(checkpoint)


def _assert_matches(got, expected):
    got = keras.ops.convert_to_numpy(got)
    assert got.shape == expected.shape
    err = float(np.abs(got - expected).max())
    assert err <= _tol(expected), f"max |keras - torch| = {err:.3e} > {_tol(expected):.3e}"


@pytest.mark.parametrize("horizon", [1, 3])
def test_predict_block_matches_the_reference_context_only(model, reference, horizon):
    _assert_matches(
        model.predict_block(reference["ctx"], reference["ctx_obs"], reference["groups"], horizon),
        reference[f"block_h{horizon}"])


def test_predict_block_matches_the_reference_with_covariates(model, reference):
    cov_ctx = reference["cov_ctx"]
    _assert_matches(
        model.predict_block(cov_ctx, np.ones_like(cov_ctx, dtype=bool), reference["cov_groups"], 2,
                            reference["roles"], reference["known"], reference["known_mask"]),
        reference["block_cov_h2"])


@pytest.mark.parametrize("clampsym", [False, True])
def test_the_forecaster_matches_the_reference(model, reference, clampsym):
    """Three decode blocks, two variates, NaNs: the refine frame and the block feedback.

    Until 2026-10-19 (D-167) ``TimestralModel._refine_block`` applied sinh a second time to
    the already sinh'd block, which moved this forecast by up to 2.4 (12% of its range).
    """
    from dl_techniques.models.time_series.timestral.forecaster import TimestralForecaster

    forecast = TimestralForecaster(model).forecast(
        reference["series"], prediction_length=70,
        symmetric_averaging=clampsym, clip_nonnegative=clampsym)
    _assert_matches(forecast.quantiles,
                    reference["forecast_clampsym" if clampsym else "forecast_raw"])
